//
// EVENT HANDLING
//
// Events are asynchronous inputs generally generated by the game user.
// Events can be discarded if no responder claims them
//
event_t         events[MAXEVENTS];
int             eventhead;
int 		eventtail;


//
// D_PostEvent
// Called by the I/O functions when input is detected
//
void D_PostEvent (event_t* ev)
{
    events[eventhead] = *ev;
    eventhead = (++eventhead)&(MAXEVENTS-1);
}


//
// D_ProcessEvents
// Send all the events of the given timestamp down the responder chain
//
void D_ProcessEvents (void)
{
    event_t*	ev;
	
    for ( ; eventtail != eventhead ; eventtail = (++eventtail)&(MAXEVENTS-1) )
    {
	ev = &events[eventtail];
	if (M_Responder (ev))
	    continue;               // menu ate the event
	G_Responder (ev);
    }
}




//
// D_Display
//  draw current display, possibly wiping it from the previous
//

// wipegamestate can be set to -1 to force a wipe on the next draw
gamestate_t     wipegamestate = GS_DEMOSCREEN;
extern  boolean setsizeneeded;
extern  int             showMessages;
void R_ExecuteSetViewSize (void);

void D_Display(void)
{
    static gamestate_t previous = -1;
    static boolean previousHelp;

    if (setsizeneeded)
        R_ExecuteSetViewSize();

    if (previous != gamestate && gamestate != GS_LEVEL)
        I_SetPalette(W_CacheLumpName("PLAYPAL", PU_CACHE));

    switch (gamestate)
    {
        case GS_LEVEL:
            if (automapactive)
                AM_Drawer();
            ST_Drawer(false, previous != GS_LEVEL || wipegamestate != GS_LEVEL
                      || previousHelp);
            if (!automapactive)
                R_RenderPlayerView(&players[displayplayer]);
            HU_Drawer();
            break;
        case GS_INTERMISSION:
            WI_Drawer();
            break;
        case GS_FINALE:
            F_Drawer();
            break;
        case GS_DEMOSCREEN:
            D_PageDrawer();
            break;
    }

    if (paused)
        V_DrawPatchDirect((SCREENWIDTH - 68) / 2, 4, 0,
                          W_CacheLumpName("M_PAUSE", PU_CACHE));

    previous = wipegamestate = gamestate;
    M_Drawer();
    previousHelp = inhelpscreens;
    I_FinishUpdate();
}

void D_DoomLoop(void)
{
    I_InitGraphics();
    int previous = I_GetTime();

    for (;;)
    {
        I_StartFrame();

        int now;
        do
            now = I_GetTime();
        while (now == previous);

        int tics = now - previous;
        previous = now;
        if (tics > 5)
            tics = 5;

        while (tics-- > 0)
        {
            I_StartTic();
            D_ProcessEvents();
            G_BuildTiccmd(&netcmds[0][gametic % BACKUPTICS]);
            if (advancedemo)
                D_DoAdvanceDemo();
            M_Ticker();
            G_Ticker();
            ++gametic;
            ++maketic;
        }

        S_UpdateSounds(players[consoleplayer].mo);
        D_Display();
    }
}

