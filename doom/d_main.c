//
// D_PageTicker
// Handles timing for warped projection
//
void D_PageTicker (void)
{
    if (--pagetic < 0)
	D_AdvanceDemo ();
}



//
// D_PageDrawer
//
void D_PageDrawer (void)
{
    V_DrawPatch (0,0, 0, W_CacheLumpName(pagename, PU_CACHE));
}


//
// D_AdvanceDemo
// Called after each demo or intro demosequence finishes
//
void D_AdvanceDemo (void)
{
    advancedemo = true;
}


//
// This cycles through the demo sequences.
// FIXME - version dependend demo numbers?
//
void D_DoAdvanceDemo(void)
{
    advancedemo = false;
    usergame = false;
    paused = false;
    gameaction = ga_nothing;
    gamestate = GS_DEMOSCREEN;
    pagetic = 35 * 8;
    demosequence = (demosequence + 1) % 2;
    pagename = demosequence == 0 ? "TITLEPIC" : "CREDIT";
    if (W_CheckNumForName(pagename) < 0)
        pagename = "TITLEPIC";
}

void D_StartTitle(void)
{
    gameaction = ga_nothing;
    demosequence = -1;
    D_AdvanceDemo();
}

void D_DoomMain(void)
{
    V_Init();
    M_LoadDefaults();
    Z_Init();
    W_InitMultipleFiles(NULL);

    if (W_CheckNumForName("MAP01") >= 0)
    {
        gamemode = commercial;
        gamemission = doom2;
    }
    else if (W_CheckNumForName("E1M1") >= 0)
    {
        if (W_CheckNumForName("E4M1") >= 0)
            gamemode = retail;
        else if (W_CheckNumForName("E2M1") >= 0)
            gamemode = registered;
        else
            gamemode = shareware;
        gamemission = doom;
    }
    else
        I_Error("IWAD: no DOOM maps");

    playeringame[0] = true;
    startskill = sk_medium;
    startepisode = startmap = 1;

    puts("M_Init");
    M_Init();
    puts("R_Init");
    R_Init();
    puts("P_Init");
    P_Init();
    I_Init();
    S_Init(0, 0);
    HU_Init();
    ST_Init();

    printf("DOOM Loopy: %d bytes free in zone\n", Z_FreeMemory());
    D_StartTitle();
    D_DoomLoop();
}
